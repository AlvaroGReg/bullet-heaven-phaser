const addTrollClub = (source: PixelFrame): PixelFrame => source.map((row, y) => row.map((pixel, x) => {
    const inHeadOutline = x >= 34 && x <= 39 && y >= 4 && y <= 10;
    const inHead = x >= 35 && x <= 38 && y >= 5 && y <= 9;
    const shaftCenter = 35 - Math.floor((y - 9) / 2);
    const inShaft = y >= 9 && y <= 22 && (x === shaftCenter || x === shaftCenter + 1);
    const shaftOutline = y >= 9 && y <= 22 && (x === shaftCenter - 1 || x === shaftCenter + 2);

    if (inHead && !(x === 35 && y === 5)) {
        return 3;
    }
    if (x === 35 && y === 5) {
        return 4;
    }
    if (inHeadOutline || shaftOutline) {
        return 1;
    }
    if (inShaft) {
        return 3;
    }

    return pixel;
}));

const addBodyArmor = (source: PixelFrame, fromRow: number, toRow: number): PixelFrame => source.map((row, y) => row.map((pixel, x) => (
    y >= fromRow && y <= toRow && x > 3 && x < row.length - 4 && pixel !== 0 && pixel !== 1 ? 9 : pixel
)));

export const ENEMY_TEXTURES = {
    boss: 'troll',
    elite: 'orc-chief',
    fast: 'goblin-dagger',
    heavy: 'orc',
    normal: 'gnoll',
    ranged: 'goblin-sling',
} as const;

export const ARMORED_ENEMY_TEXTURES = {
    elite: 'orc-chief-armored',
    heavy: 'orc-armored',
    normal: 'gnoll-armored',
} as const;

export function createEnemyTextures(scene: Phaser.Scene): void {
    renderSpriteSheet(scene, ENEMY_TEXTURES.normal, [GNOLL], PALETTE, 2);
    renderSpriteSheet(scene, ENEMY_TEXTURES.fast, [GOBLIN_DAGGER], PALETTE, 2);
    renderSpriteSheet(scene, ENEMY_TEXTURES.heavy, [ORC], PALETTE, 2);
    renderSpriteSheet(scene, ENEMY_TEXTURES.elite, [ORC_CHIEF], PALETTE, 2);
    renderSpriteSheet(scene, ENEMY_TEXTURES.ranged, [GOBLIN_SLING], PALETTE, 2);
    renderSpriteSheet(scene, ENEMY_TEXTURES.boss, [addTrollClub(TROLL)], PALETTE, 2);
    renderSpriteSheet(scene, ARMORED_ENEMY_TEXTURES.normal, [addBodyArmor(GNOLL, 9, 14)], PALETTE, 2);
    renderSpriteSheet(scene, ARMORED_ENEMY_TEXTURES.heavy, [addBodyArmor(ORC, 11, 17)], PALETTE, 2);
    renderSpriteSheet(scene, ARMORED_ENEMY_TEXTURES.elite, [addBodyArmor(ORC_CHIEF, 11, 18)], PALETTE, 2);
}
